-- 008_facility_reports.sql
-- Equipment / PC problem reports.
--
-- Faculty can report a broken PC or a room/equipment problem. MIS staff and
-- admins review those reports from Facility Issues and either apply
-- maintenance, clear it, or dismiss the report. Resolving a report also
-- notifies the reporter.
--
-- Rooms and computers keep their existing maintenance flags; a report is the
-- request, the flag is the operational state.

create table if not exists facility_reports (
    id bigint generated by default as identity primary key,
    reported_by bigint not null references users(id) on delete cascade,
    room_id bigint references rooms(id) on delete cascade,
    computer_id integer references computers(id) on delete cascade,
    description text not null,
    status text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
    resolution_note text,
    resolved_by bigint references users(id) on delete set null,
    resolved_at timestamptz,
    created_at timestamptz not null default now(),
    constraint facility_reports_target_check check (room_id is not null or computer_id is not null),
    constraint facility_reports_description_check check (char_length(btrim(description)) between 3 and 500)
);

create index if not exists facility_reports_status_idx
    on facility_reports (status, created_at desc);
create index if not exists facility_reports_reporter_idx
    on facility_reports (reported_by, created_at desc);

alter table facility_reports enable row level security;

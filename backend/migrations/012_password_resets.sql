-- 012_password_resets.sql
-- Single-use password reset tokens.
--
-- Only the SHA-256 hash of the token is stored. A request is valid until it is
-- used or expires (60 minutes). Admins can issue a fresh link from User
-- Management when email delivery is not configured.

create table if not exists password_resets (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id) on delete cascade,
    token_hash text not null unique,
    expires_at timestamptz not null,
    used_at timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists password_resets_user_idx
    on password_resets (user_id, expires_at desc);
create index if not exists password_resets_token_idx
    on password_resets (token_hash);

alter table password_resets enable row level security;

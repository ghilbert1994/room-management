-- 010_facility_report_attachments.sql
-- Evidence attached to facility reports.
--
-- Photos and short videos are stored as bytes so they survive redeploys
-- (Render's local disk is ephemeral). The API enforces a per-file and total
-- size limit; see backend/routes/facility.js.

create table if not exists facility_report_attachments (
    id bigint generated by default as identity primary key,
    report_id bigint not null references facility_reports(id) on delete cascade,
    file_name text not null,
    mime_type text not null,
    size_bytes integer not null check (size_bytes > 0),
    data bytea not null,
    created_at timestamptz not null default now()
);

create index if not exists facility_report_attachments_report_idx
    on facility_report_attachments (report_id);

alter table facility_report_attachments enable row level security;

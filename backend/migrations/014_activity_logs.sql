-- 014_activity_logs.sql
-- Append-only audit trail for admin review.
--
-- Every row keeps a snapshot of the actor (name, email, role) so the log stays
-- readable even if the account is renamed or deactivated later.

create table if not exists activity_logs (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id) on delete set null,
    actor_name text,
    actor_email text,
    actor_role text,
    action text not null,
    entity_type text,
    entity_id text,
    description text not null,
    metadata jsonb not null default '{}'::jsonb,
    ip_address text,
    user_agent text,
    created_at timestamptz not null default now()
);

create index if not exists activity_logs_created_idx
    on activity_logs (created_at desc);
create index if not exists activity_logs_user_idx
    on activity_logs (user_id, created_at desc);
create index if not exists activity_logs_action_idx
    on activity_logs (action, created_at desc);
create index if not exists activity_logs_entity_idx
    on activity_logs (entity_type, entity_id);

alter table activity_logs enable row level security;

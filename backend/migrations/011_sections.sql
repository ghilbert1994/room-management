-- 011_sections.sql
-- Class sections (e.g. BSIT 1st Year A) used by students, reservations, and
-- facility reports.
--
-- Sections are seeded from existing class schedule entries and kept in sync
-- whenever an admin adds or edits a class entry.

create table if not exists sections (
    id bigint generated by default as identity primary key,
    course text not null,
    year_level text not null,
    name text not null,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    constraint sections_unique_label unique (course, year_level, name)
);

insert into sections (course, year_level, name)
select distinct trim(course), trim(year_level), trim(section)
from semester_schedules
where trim(course) <> '' and trim(section) <> ''
on conflict (course, year_level, name) do nothing;

alter table users add column if not exists section_id bigint references sections(id) on delete set null;
alter table reservations add column if not exists section_id bigint references sections(id) on delete set null;
alter table facility_reports add column if not exists section_id bigint references sections(id) on delete set null;

create index if not exists users_section_idx on users (section_id);
create index if not exists reservations_section_idx on reservations (section_id);
create index if not exists facility_reports_section_idx on facility_reports (section_id);

alter table sections enable row level security;

-- 006_reservation_purposes.sql
-- First-normal-form clean-up for reservation purposes.
--
-- Before this migration `reservations.purpose` was free text, so the same
-- intent was stored as "Ya", "Ya 3", "hahahahaha", ... That made aggregation
-- impossible and let meaningless values into the database. Purposes now live
-- in their own relation and reservations reference it with a foreign key.
--
-- This migration is additive and safe to run while the previous backend is
-- still live: the legacy `purpose` column is left in place (it is dropped by
-- 007 once the new backend is deployed).
--
-- See docs/DATABASE_NORMALIZATION.md for the 1NF/2NF/3NF write-up.

create table if not exists reservation_purposes (
    id bigint generated by default as identity primary key,
    label text not null unique,
    description text,
    is_active boolean not null default true,
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

comment on table reservation_purposes is 'Controlled vocabulary for reservation purposes (1NF: atomic, single-valued, FK-referenced).';

insert into reservation_purposes (label, description, sort_order) values
    ('Class Use', 'Regular class activity in a laboratory', 10),
    ('Capstone / Thesis Defense', 'Capstone or thesis defense and consultation', 20),
    ('Project Meeting', 'Group project or team meeting', 30),
    ('Research Work', 'Research data gathering or experimentation', 40),
    ('Seminar / Workshop', 'Seminar, workshop, or training session', 50),
    ('Training', 'Skills training or orientation', 60),
    ('Examination', 'Quiz, exam, or assessment', 70),
    ('Make-up Class', 'Rescheduled or make-up class session', 80),
    ('Organization Activity', 'Student organization or council activity', 90),
    ('Others', 'Any other purpose, described in purpose_notes', 999)
on conflict (label) do nothing;

-- The controlled reference plus the free-text "specify" field. Keeping the
-- optional note separate means the analytical column stays clean.
alter table reservations
    add column if not exists purpose_id bigint references reservation_purposes(id) on delete restrict;
alter table reservations
    add column if not exists purpose_notes text;

comment on column reservations.purpose_id is 'FK to reservation_purposes; the controlled purpose category';
comment on column reservations.purpose_notes is 'Optional detail, required in the UI when purpose_id points to "Others"';

-- Backfill: exact label matches keep their original meaning.
update reservations r
set purpose_id = p.id
from reservation_purposes p
where r.purpose_id is null
  and r.purpose is not null
  and lower(trim(r.purpose)) = lower(p.label);

-- Near-matches ("Exam", "Capstone Project meeting", "Morning class", ...) are
-- mapped to the closest category so reports stay useful.
update reservations r
set purpose_id = p.id
from reservation_purposes p
where r.purpose_id is null
  and r.purpose is not null
  and p.label = case
      when r.purpose ilike '%capstone%' or r.purpose ilike '%thesis%' then 'Capstone / Thesis Defense'
      when r.purpose ilike '%exam%' then 'Examination'
      when r.purpose ilike '%seminar%' or r.purpose ilike '%workshop%' then 'Seminar / Workshop'
      when r.purpose ilike '%training%' or r.purpose ilike '%orientation%' then 'Training'
      when r.purpose ilike '%meeting%' then 'Project Meeting'
      when r.purpose ilike '%class%' then 'Class Use'
  end;

-- Anything that did not match a known label is preserved as a note and filed
-- under "Others" so no historical detail is lost.
update reservations r
set purpose_notes = trim(r.purpose)
where r.purpose_notes is null
  and r.purpose_id is null
  and r.purpose is not null
  and trim(r.purpose) <> '';

update reservations
set purpose_id = (select id from reservation_purposes where label = 'Others')
where purpose_id is null;

create index if not exists reservations_purpose_idx on reservations (purpose_id);
